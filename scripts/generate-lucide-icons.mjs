const rootPackageJson = JSON.parse(await readFile(
  path.join(root, 'package.json'),
  'utf8'
));
const expectedVersion = rootPackageJson.devDependencies?.['lucide-react'];
if ('string' !== typeof expectedVersion || !/^\d+\.\d+\.\d+$/.test(expectedVersion)) {
  throw new Error('lucide-react-development-version-invalid');
}
if (Object.hasOwn(rootPackageJson.dependencies ?? {}, 'lucide-react')) {
  throw new Error('lucide-react-must-not-be-runtime-dependency');
}

const packageJson = JSON.parse(await readFile(
  path.join(root, 'node_modules/lucide-react/package.json'),
  'utf8'
));
if (expectedVersion !== packageJson.version) {
  throw new Error(`lucide-react-version-invalid:${expectedVersion}:${packageJson.version}`);
}

const nodes = {};
for (const [name, file] of Object.entries(icons)) {
  const modulePath = path.join(root, `node_modules/lucide-react/dist/esm/icons/${file}.js`);
  const module = await import(`${pathToFileURL(modulePath).href}?v=${expectedVersion}`);
  if (!Array.isArray(module.__iconNode)) throw new Error(`lucide-icon-node-invalid:${name}`);
  nodes[name] = module.__iconNode;
}

const source = `/* Generated by scripts/generate-lucide-icons.mjs from lucide-react ${expectedVersion}. */
import { createElement } from '@wordpress/element';
import type { SVGProps } from 'react';

export type LucideIcon = (props: Readonly<SVGProps<SVGSVGElement> & {
  size?: number;
  strokeWidth?: number;
}>) => JSX.Element;

function icon(node: ReadonlyArray<readonly [string, Readonly<Record<string, string | number>>]>): LucideIcon {
  return function LucideIcon({ size = 24, strokeWidth = 2, ...props }) {
    return (
      <svg
        aria-hidden="true"
        focusable="false"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        {...props}
      >
        {node.map(([tag, attributes]) => createElement(tag, attributes))}
      </svg>
    );
  };
}

${Object.entries(nodes).map(([name, node]) => (
  `export const ${name} = icon(${JSON.stringify(node)});`
)).join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== source) throw new Error('generated-lucide-icons-outdated');
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, 'utf8');
}
