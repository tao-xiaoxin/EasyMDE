import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Official Unicode Character Database inputs. Normal builds never fetch these.
const inputs = [
  [11, '64f117a4749dd4a1b6c54277f63f6cf1e0eb45d290cbedaf777fbe71b8880885', 1480],
  [13, '99d231d7c91688bbe8ca8ccebcc2f46b5b222f844babe4827295bae11e2abe5f', 1490],
  [14, 'a566cd48687b2cd897e02501118b2413c14ae86d318f9abbbba97feb84189f0f', 1530],
  [16, '6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb', 1557],
  [17, 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183', 1585],
];
const output = fileURLToPath(new URL('../frontend/src/features/editor-context-menu/reference-case-fold-data.ts', import.meta.url));

async function generate() {
  const merged = new Map();
  for (const [profile, hash, count] of inputs) {
    const url = `https://www.unicode.org/Public/${profile}.0.0/ucd/CaseFolding.txt`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Unicode case-fold input unavailable: ${profile}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (createHash('sha256').update(bytes).digest('hex') !== hash) throw new Error(`Unicode case-fold checksum mismatch: ${profile}`);
    const current = new Map();
    for (const line of bytes.toString('utf8').split('\n')) {
      const parts = line.split('#', 1)[0]?.trim().split(';').map((part) => part.trim());
      if (!parts || !['C', 'F'].includes(parts[1])) continue;
      const code = Number.parseInt(parts[0], 16);
      const fold = parts[2].split(/\s+/u).map((part) => Number.parseInt(part, 16));
      if (!Number.isInteger(code) || fold.some((item) => !Number.isInteger(item)) || current.has(code)) {
        throw new Error(`Unicode case-fold input invalid: ${profile}`);
      }
      current.set(code, fold);
    }
    if (current.size !== count) throw new Error(`Unicode case-fold input count mismatch: ${profile}`);
    for (const [code, previous] of merged) {
      if (JSON.stringify(current.get(code)) !== JSON.stringify(previous.fold)) {
        throw new Error(`Unicode case-fold input changed an earlier mapping: ${profile}`);
      }
    }
    for (const [code, fold] of current) {
      if (!merged.has(code)) merged.set(code, { fold, profile });
    }
  }
  const rows = [...merged.entries()].sort(([a], [b]) => a - b)
    .map(([code, { fold, profile }]) => [code, fold, profile]);
  return `// Generated by scripts/generate-reference-case-fold.mjs from the Unicode Character Database.\n`
    + `// See THIRD-PARTY-NOTICES.md for attribution and license.\n`
    + `export const referenceCaseFoldData: ReadonlyArray<readonly [number, readonly number[], number]> = ${JSON.stringify(rows)};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv[2] ?? '--check';
  if (!['--write', '--check'].includes(mode)) throw new Error('Invalid reference case-fold generator mode');
  const expected = await generate();
  if ('--write' === mode) await writeFile(output, expected);
  else if (await readFile(output, 'utf8') !== expected) throw new Error('Reference case-fold data is out of date');
}
